// Builds brand/tokens.css and brand/flutter/ember_tokens.dart from brand/tokens.json.
// Usage: node brand/tools/build.mjs   (no dependencies)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const T = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));
const entries = (g) => Object.entries(g).filter(([k]) => !k.startsWith('$'));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const dartId = (s) => { const c = camel(s); return /^[0-9]/.test(c) ? c.replace(/^2/, 'x') : c; };
const px = (n) => `${n}px`;

/* ---------- CSS ---------- */
const shadowCss = (list) => list.map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.color}`).join(', ');
const themeVars = (mode) => [
  ...entries(T.color).map(([k, v]) => `  --${k}: ${v[mode]};`),
  ...entries(T.shadow).map(([k, v]) => `  --shadow-${k}: ${shadowCss(v[mode])};`),
].join('\n');
const fam = (f) => T.font[f].$value.map((x) => (/\s/.test(x) || /^[A-Z]/.test(x) && !x.includes('-') && x !== 'Georgia' ? `"${x}"` : x)).join(', ');
const shared = [
  ...entries(T.font).map(([k]) => `  --font-${k}: ${fam(k)};`),
  ...entries(T.radius).map(([k, v]) => `  --radius-${k}: ${px(v.$value)};`),
  ...entries(T.space).map(([k, v]) => `  --space-${k}: ${px(v.$value)};`),
  ...entries(T.size).map(([k, v]) => `  --size-${k}: ${k === 'icon-stroke' ? v.$value : px(v.$value)};`),
  `  --motion-panel: ${T.motion['panel-duration'].$value};`,
  `  --ease-panel: cubic-bezier(${T.motion['panel-ease'].$value.join(', ')});`,
].join('\n');
const typeVars = entries(T.type).map(([k, { $value: t }]) =>
  `  --type-${k}: ${t.weight} ${t.size}px/${t.lineHeight} var(--font-${t.family});` + (t.letterSpacing ? `\n  --type-${k}-tracking: ${t.letterSpacing};` : '')).join('\n');

const css = `/* GENERATED by brand/tools/build.mjs from brand/tokens.json. Edit the JSON, not this file. */
@font-face { font-family: "Geist"; src: url("fonts/geist-latin.woff2") format("woff2"); font-weight: 100 900; font-display: swap; }
@font-face { font-family: "Literata"; src: url("fonts/literata-latin.woff2") format("woff2"); font-weight: 200 900; font-display: swap; }
@font-face { font-family: "Literata"; src: url("fonts/literata-italic-latin.woff2") format("woff2"); font-weight: 200 900; font-style: italic; font-display: swap; }

:root {
${shared}
${typeVars}
}

/* Dark is the default; set data-theme="light" on <html> (or any subtree) for the light room. */
:root, [data-theme="dark"] {
  color-scheme: dark;
${themeVars('dark')}
}
[data-theme="light"] {
  color-scheme: light;
${themeVars('light')}
}
/* Follow the OS only when the app has not chosen a theme. */
@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
    color-scheme: light;
${themeVars('light').replace(/^ {2}/gm, '    ')}
  }
}
`;
writeFileSync(join(root, 'tokens.css'), css);

/* ---------- Dart ---------- */
function dartColor(v) {
  let r, g, b, a = 1; const h = v.match(/^#([0-9a-f]{6})$/i);
  if (h) { const n = parseInt(h[1], 16); r = n >> 16; g = (n >> 8) & 255; b = n & 255; }
  else { const m = v.match(/^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/); if (!m) throw new Error('colour ' + v); [r, g, b, a] = [+m[1], +m[2], +m[3], +m[4]]; }
  const hex = (x) => x.toString(16).padStart(2, '0').toUpperCase();
  return `Color(0x${hex(Math.round(a * 255))}${hex(r)}${hex(g)}${hex(b)})`;
}
const cols = entries(T.color).map(([k, v]) => ({ id: dartId(k), name: k, desc: v.$description, dark: dartColor(v.dark), light: dartColor(v.light) }));
const shadowDart = (list) => `[${list.map((s) => `BoxShadow(color: ${dartColor(s.color)}, offset: Offset(${s.x}, ${s.y}), blurRadius: ${s.blur})`).join(', ')}]`;
const num = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);
const famName = (f) => T.font[f].$value[0];
const typeDart = entries(T.type).map(([k, { $value: t }]) => {
  const ls = t.letterSpacing ? `, letterSpacing: ${num(Math.round(parseFloat(t.letterSpacing) * t.size * 1000) / 1000)}` : '';
  const ff = t.tabularFigures ? ', fontFeatures: [FontFeature.tabularFigures()]' : '';
  const fb = T.font[t.family].$value.slice(1).filter((x) => !/^(system-ui|sans-serif|serif|monospace|ui-monospace)$/.test(x)).map((x) => `'${x}'`);
  const fbs = fb.length ? `, fontFamilyFallback: [${fb.join(', ')}]` : '';
  return `  static const TextStyle ${dartId(k)} = TextStyle(fontFamily: '${famName(t.family)}'${fbs}, fontSize: ${num(t.size)}, fontWeight: FontWeight.w${t.weight}, height: ${num(t.lineHeight)}${ls}${ff});`;
}).join('\n');
const dims = (cls, g, doc) => `/// ${doc}\nabstract final class ${cls} {\n${entries(g).map(([k, v]) => `  static const double ${dartId(k)} = ${num(v.$value)};`).join('\n')}\n}`;
const [c1, c2, c3, c4] = T.motion['panel-ease'].$value;

const dart = `// GENERATED by brand/tools/build.mjs from brand/tokens.json. Edit the JSON, not this file.
// ignore_for_file: public_member_api_docs
import 'dart:ui' show FontFeature;

import 'package:flutter/material.dart';

/// Ember colour roles. One name, two rooms: [EmberColors.dark] and [EmberColors.light].
/// Read it with \`Theme.of(context).extension<EmberColors>()!\`.
@immutable
class EmberColors extends ThemeExtension<EmberColors> {
  const EmberColors({
${cols.map((c) => `    required this.${c.id},`).join('\n')}
  });

${cols.map((c) => `${c.desc ? `  /// ${c.desc}.\n` : ''}  final Color ${c.id};`).join('\n')}

  static const EmberColors dark = EmberColors(
${cols.map((c) => `    ${c.id}: ${c.dark},`).join('\n')}
  );

  static const EmberColors light = EmberColors(
${cols.map((c) => `    ${c.id}: ${c.light},`).join('\n')}
  );

  @override
  EmberColors copyWith({
${cols.map((c) => `    Color? ${c.id},`).join('\n')}
  }) =>
      EmberColors(
${cols.map((c) => `        ${c.id}: ${c.id} ?? this.${c.id},`).join('\n')}
      );

  @override
  EmberColors lerp(ThemeExtension<EmberColors>? other, double t) {
    if (other is! EmberColors) return this;
    return EmberColors(
${cols.map((c) => `      ${c.id}: Color.lerp(${c.id}, other.${c.id}, t)!,`).join('\n')}
    );
  }
}

/// Shadows exist only on floating layers (The Flat Desk Rule).
abstract final class EmberShadows {
  static const List<BoxShadow> floatDark = ${shadowDart(T.shadow.float.dark)};
  static const List<BoxShadow> floatLight = ${shadowDart(T.shadow.float.light)};
  static const List<BoxShadow> seatedDark = ${shadowDart(T.shadow.seated.dark)};
  static const List<BoxShadow> seatedLight = ${shadowDart(T.shadow.seated.light)};
}

/// Two voices: Literata for content the user wrote, Geist for the tool.
abstract final class EmberType {
  static const String sans = '${famName('sans')}';
  static const String serif = '${famName('serif')}';
${typeDart}
}

${dims('EmberRadius', T.radius, 'Corner radii. Pills are for controls; containers get soft corners.')}

${dims('EmberSpace', T.space, 'A 4px rhythm with frequent 6/10/14px half-steps.')}

${dims('EmberSize', T.size, 'Fixed component and shell sizes.')}

/// The one motion family: panels slide, stretch and collapse. Nothing else animates.
abstract final class EmberMotion {
  static const Duration panel = Duration(milliseconds: ${parseInt(T.motion['panel-duration'].$value, 10)});
  static const Curve panelEase = Cubic(${c1}, ${c2}, ${c3}, ${c4});
}
`;
mkdirSync(join(root, 'flutter'), { recursive: true });
writeFileSync(join(root, 'flutter', 'ember_tokens.dart'), dart);
console.log('wrote tokens.css and flutter/ember_tokens.dart:', cols.length, 'colour roles');
